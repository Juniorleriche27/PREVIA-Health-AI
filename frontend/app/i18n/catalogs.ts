export function translateLiteral(value: string, language: Language): string {
  if (language === "en" || !value) return value;
  const exact = fr[value];
  if (exact) return exact;
  const trimmed = fr[value.trim()];
  if (trimmed) return trimmed;
  const normalizedSpaces = fr[value.replace(/\s+/g, " ").trim()];
  if (normalizedSpaces) return normalizedSpaces;
  const unUnderscored = fr[value.replace(/_/g, " ").trim()];
  if (unUnderscored) return unUnderscored;
  const prefixes: Array<[string, string]> = [
    ["Selected provider: ", "Fournisseur sélectionné : "],
    ["Check FastAPI on port ", "Vérifiez FastAPI sur le port "],
    ["Check FastAPI at ", "Vérifiez FastAPI à l'adresse "],
    ["Scenarios: ", "Scénarios : "],
    ["From the existing strategy engine", "Issus du moteur de stratégie existant"],
    ["of fictitious selection", "de la sélection fictive"],
    ["of selected", "des sélectionnés"],
  ];
  for (const [source, target] of prefixes) {
    if (value.startsWith(source)) return target + value.slice(source.length);
    if (value.includes(source)) return value.replace(source, target);
  }
  return value;
}

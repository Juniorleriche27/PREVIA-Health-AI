"""Local SHAP explanations for the *frozen* cross-cycle NHANES research model.

The model is never fitted or optimized here. Only local trusted joblib files
created by PREVIA's training pipeline are loaded. No personal records persist.
"""
from __future__ import annotations

from functools import lru_cache
import hashlib
import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

FEATURES = [
    "age", "sex", "bmi", "sbp", "smoking", "waist_cm",
    "hypertension_history", "high_cholesterol_history",
    "leisure_activity", "work_activity",
]
NUMERIC = {"age", "bmi", "sbp", "waist_cm"}
CATEGORIES = {
    "sex": {"male", "female"},
    "smoking": {"never", "former", "current"},
    "hypertension_history": {"yes", "no"},
    "high_cholesterol_history": {"yes", "no"},
    "leisure_activity": {"yes", "no"},
    "work_activity": {"yes", "no"},
}


class ModelNotAvailable(RuntimeError):
    """A trusted, compatible local model is not yet available."""


def model_locations(root: Path) -> tuple[Path, Path, Path]:
    out = root / "PREVIA_ML_Validation_Externe" / "results" / "cross_cycle"
    return (
        out / "PREVIA_HBA1C_MODEL_CROSS_CYCLE.joblib",
        out / "DEVELOPMENT_FROZEN.json",
        out / "SCORES_VALIDATION_EXTERNE.json",
    )


def _digest(file: Path) -> str:
    with file.open("rb") as stream:
        h = hashlib.sha256()
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


@lru_cache(maxsize=2)
def _load_cached(root_str: str, signature: tuple[str, int, int, int]):
    import joblib
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.pipeline import Pipeline
    root = Path(root_str)
    model_file, freeze_file, scores_file = model_locations(root)
    if not (model_file.is_file() and freeze_file.is_file()):
        raise ModelNotAvailable("Entraîne d'abord PREVIA_ML_Validation_Externe sur ton PC : fichier modèle ou protocole figé introuvable.")
    freeze = json.loads(freeze_file.read_text(encoding="utf-8"))
    winner = freeze.get("winner")
    spec = freeze.get("candidate_decisions", {}).get(winner, {})
    features = spec.get("features")
    if winner != "extended_random_forest" or features != FEATURES:
        raise ModelNotAvailable("Le modèle local n'est pas le Random Forest enrichi attendu par ce module SHAP.")
    threshold = spec.get("oof_screening_threshold")
    if not isinstance(threshold, (int, float)) or not 0 < threshold < 1:
        raise ModelNotAvailable("Le seuil figé du protocole n'est pas valide.")
    # joblib is pickle-backed: never load an uploaded/untrusted model.
    model = joblib.load(model_file)
    if not isinstance(model, Pipeline) or not {"prep", "model"}.issubset(model.named_steps):
        raise ModelNotAvailable("L'artefact modèle n'est pas un pipeline PREVIA valide.")
    if not isinstance(model.named_steps["model"], RandomForestClassifier):
        raise ModelNotAvailable("L'explication SHAP nécessite le modèle Random Forest pré-entraîné.")
    if list(model.feature_names_in_) != features:
        raise ModelNotAvailable("La signature des colonnes ne correspond pas au protocole figé.")
    scores = {}
    if scores_file.is_file():
        try:
            scores = json.loads(scores_file.read_text(encoding="utf-8"))
        except (ValueError, OSError):
            scores = {}
    return model, float(threshold), freeze, scores, _digest(model_file)


def load_model(root: Path):
    model_file, freeze_file, _ = model_locations(root)
    if not (model_file.is_file() and freeze_file.is_file()):
        raise ModelNotAvailable("Le modèle NHANES v2 est absent. Exécute d'abord le pipeline cross-cycle sur Windows.")
    signature = (str(model_file), model_file.stat().st_mtime_ns, freeze_file.stat().st_mtime_ns, model_file.stat().st_size)
    return _load_cached(str(root.resolve()), signature)


def _one_row(values: dict[str, Any]) -> pd.DataFrame:
    clean: dict[str, Any] = {}
    for name in FEATURES:
        val = values.get(name)
        if val is None or val == "unknown":
            clean[name] = np.nan
        elif name in NUMERIC:
            clean[name] = float(val)
        else:
            if val not in CATEGORIES[name]:
                raise ValueError(f"Valeur non prise en charge : {name}")
            clean[name] = val
    if not 40 <= clean["age"] <= 74:
        raise ValueError("Âge hors du domaine 40–74 ans.")
    return pd.DataFrame([clean], columns=FEATURES)


def _feature_of(transformed_name: str) -> str:
    # Generated by ColumnTransformer: num__age, num__missingindicator_bmi,
    # cat__sex_female etc. Check every transformed column is explained.
    if transformed_name.startswith("num__missingindicator_"):
        name = transformed_name.removeprefix("num__missingindicator_")
        if name in NUMERIC:
            return name
    if transformed_name.startswith("num__"):
        name = transformed_name.removeprefix("num__")
        if name in NUMERIC:
            return name
    if transformed_name.startswith("cat__"):
        encoded = transformed_name.removeprefix("cat__")
        for name in sorted(CATEGORIES, key=len, reverse=True):
            if encoded.startswith(name + "_"):
                return name
    raise ValueError(f"Variable transformée non mappée : {transformed_name}")


def _extract_shap_class_1(explainer, transformed: np.ndarray) -> tuple[float, np.ndarray]:
    import shap
    values = explainer.shap_values(transformed, check_additivity=False)
    if isinstance(values, list):
        positive = np.asarray(values[1])[0]
    else:
        array = np.asarray(values)
        positive = array[0, :, 1] if array.ndim == 3 else array[0]
    baseline = np.asarray(explainer.expected_value).ravel()
    return float(baseline[-1]), np.asarray(positive, dtype=float)


def explain(root: Path, values: dict[str, Any]) -> dict[str, Any]:
    import shap
    model, threshold, freeze, scores, model_hash = load_model(root)
    row = _one_row(values)
    preprocessor = model.named_steps["prep"]
    forest = model.named_steps["model"]
    transformed = np.asarray(preprocessor.transform(row), dtype=float)
    transformed_names = list(preprocessor.get_feature_names_out())
    if transformed.shape[1] != len(transformed_names):
        raise ValueError("Dimension des caractéristiques incohérente.")
    baseline, shap_values = _extract_shap_class_1(shap.TreeExplainer(forest), transformed)
    if len(shap_values) != len(transformed_names):
        raise ValueError("Dimension SHAP incohérente.")
    individual_probability = float(model.predict_proba(row)[0, 1])
    residual = abs(baseline + float(np.sum(shap_values)) - individual_probability)
    if residual > 1e-5:
        raise ValueError(f"Échec du contrôle d'additivité SHAP ({residual:.5g}).")
    grouped: dict[str, float] = dict.fromkeys(FEATURES, 0.0)
    for name, impact in zip(transformed_names, shap_values):
        grouped[_feature_of(name)] += float(impact)
    ordered = sorted(grouped.items(), key=lambda pair: abs(pair[1]), reverse=True)
    external = scores.get("external", {}).get("winner_scores", {})
    return {
        "task": "Association with observed NHANES HbA1c >= 5.7%; NOT future CVD or diabetes prediction",
        "data_type": "research-only; demonstration with fabricated inputs",
        "model": freeze["winner"],
        "model_sha256": model_hash,
        "selection_sha256": freeze.get("selection_sha256"),
        "probability_unvalidated_percent": round(individual_probability * 100, 2),
        "experimental_threshold": round(threshold, 5),
        "above_experimental_threshold": individual_probability >= threshold,
        "shap_baseline_percent": round(baseline * 100, 3),
        "contributions": [{"feature": k, "impact_percentage_points": round(v * 100, 4)} for k, v in ordered],
        "shap_additivity_error": round(residual, 10),
        "external_reference_metrics": {
            k: round(float(external[k]), 4)
            for k in ("roc_auc", "pr_auc_ap", "sensitivity", "specificity") if isinstance(external.get(k), (int, float))
        },
        "limitations": [
            "SHAP explains the fitted model output, not a biological cause or an individual clinical finding.",
            "Model trained on unweighted US NHANES 2017–18, evaluated on 2015–16; not validated for Togo.",
            "This is classification of a concurrently measured lab value; it does not predict future disease.",
            "The threshold was selected during development for research and is not clinical screening guidance.",
            "The submitted inputs are neither retained nor written to disk by this API.",
        ],
    }
